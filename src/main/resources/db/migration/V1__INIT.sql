CREATE TABLE IF NOT EXISTS user_onboardings
(
    id                 bigint generated by default as identity
        primary key,
    created_at         timestamp(6) not null,
    updated_at         timestamp(6) not null,
    user_id            bigint       not null
        unique
        constraint fk_user_onboardings_user
            references users,
    hiking_level       varchar(20)  not null
        constraint user_onboardings_hiking_level_check
            check ((hiking_level)::text = ANY
                   ((ARRAY ['BEGINNER'::character varying, 'INTERMEDIATE'::character varying, 'EXPERT'::character varying])::text[])),
    exercise_type      varchar(30)  not null
        constraint user_onboardings_exercise_type_check
            check ((exercise_type)::text = ANY
                   ((ARRAY ['GYM'::character varying, 'CARDIO'::character varying, 'HOME_TRAINING'::character varying, 'PILATES'::character varying, 'YOGA'::character varying, 'WALKING_HIKING'::character varying, 'SPORTS'::character varying, 'CROSSFIT'::character varying, 'SWIMMING'::character varying, 'NONE'::character varying])::text[])),
    exercise_frequency varchar(30)
        constraint user_onboardings_exercise_frequency_check
            check ((exercise_frequency IS NULL) OR ((exercise_frequency)::text = ANY
                                                    ((ARRAY ['DAILY'::character varying, 'WEEK_3_4'::character varying, 'WEEK_1_2'::character varying, 'MONTH_1_2'::character varying, 'LESS_THAN_MONTH_1'::character varying])::text[]))),
    exercise_duration  varchar(30)
        constraint user_onboardings_exercise_duration_check
            check ((exercise_duration IS NULL) OR ((exercise_duration)::text = ANY
                                                   ((ARRAY ['OVER_4H'::character varying, 'HOUR_2_4'::character varying, 'HOUR_1_2'::character varying, 'UNDER_1H'::character varying])::text[])))
);

