CREATE TABLE IF NOT EXISTS users
(
    id                bigint generated by default as identity
        primary key,
    created_at        timestamp(6)           not null,
    updated_at        timestamp(6)           not null,
    age               integer,
    is_deleted        boolean                not null,
    device_type       device_type_enum       not null,
    email             varchar(50),
    fcm_token         varchar(255),
    gender            gender_enum,
    name              varchar(30),
    oauth_id          varchar(255)           not null,
    oauth_provider    oauth_provider_enum    not null,
    onboarding_status onboarding_status_enum not null,
    profile_url       varchar(255),
    weight            double precision,
    nickname          varchar(30),
    birth_date        date,
    height            double precision,
    refresh_token     varchar(512),
    constraint users_pk
        unique (oauth_id, oauth_provider)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_users_active_nickname
    on users (nickname)
    where ((nickname IS NOT NULL) AND (is_deleted = false));

